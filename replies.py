def _has(pattern, text):
    return re.search(pattern, text, re.IGNORECASE) is not None


def _only_mentions(text):
    """Комментарий состоит только из отметок друзей (розыгрыши) — игнорируем."""
    stripped = re.sub(r"@[\w.]+", "", text).strip()
    return text.strip().startswith("@") and len(stripped) < 3


def classify_comment(text):
    """Возвращает (ответ_в_комментарии, личное_сообщение) или None, если не отвечаем."""
    t = (text or "").strip()
    if not t or _only_mentions(t):
        return None
    if _has(_COURSE, t):
        return COMMENT_REPLY_COURSE, DM_COURSE
    if _has(_PROGRAM, t):
        # Не называем программу — зовём в директ, там рассказываем про курс
        return "Расскажу подробнее в директ 📩", DM_PROGRAM
    if _has(_INTEREST, t):
        return COMMENT_REPLY_INTEREST, PRIVATE_REPLY_CATALOG
    if _has(_THANKS, t) or not re.search(r"[A-Za-zА-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІі]", t):
        # благодарность или только эмодзи
        return COMMENT_REPLY_THANKS, None
    return COMMENT_REPLY_INTEREST, PRIVATE_REPLY_CATALOG


def classify_dm(text, first_contact):
    """Ответ на сообщение в директе или None.
    first_contact=True — человек пишет впервые (мы ему ещё ничего не писали)."""
    t = (text or "").strip()
    if _has(_COURSE, t):
        return DM_COURSE
    if _has(_PRICE, t):
        return DM_PRICES
    if _has(_PROGRAM, t):
        return DM_PROGRAM
