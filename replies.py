def _words(t):
    return re.findall(r"[^\W\d_]{2,}", t)


def needs_ai(text):
    """Настоящий вопрос/фраза (а не эмодзи, «+», «цена», отметки) — отвечает нейросеть."""
    t = (text or "").strip()
    if not t or _only_mentions(t):
        return False
    return len(_words(t)) >= 3 or ("?" in t and len(_words(t)) >= 2)


